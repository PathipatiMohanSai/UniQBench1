$Execution = Split-Path -Parent $MyInvocation.MyCommand.Path
$Final = Join-Path $Execution "results_mnist_final_comparison_v1"
$Processed = Join-Path $Final "processed"
$RawPath = Join-Path $Final "raw\benchmark_runs.csv"
$AggregatePath = Join-Path $Processed "aggregate_results.csv"
$OverallPath = Join-Path $Processed "overall_summary.csv"
$SvmRunsPath = Join-Path $Processed "classical_svm_runs.csv"
$SvmSummaryPath = Join-Path $Processed "classical_svm_summary.csv"

foreach ($Path in @($RawPath, $AggregatePath, $OverallPath, $SvmRunsPath, $SvmSummaryPath)) {
    if (!(Test-Path -LiteralPath $Path)) {
        throw "Required frozen CSV is missing: $Path"
    }
}

$Raw = @(Import-Csv -LiteralPath $RawPath)
$Aggregate = @(Import-Csv -LiteralPath $AggregatePath)
$Overall = @(Import-Csv -LiteralPath $OverallPath)
$SvmRuns = @(Import-Csv -LiteralPath $SvmRunsPath)
$SvmSummary = @(Import-Csv -LiteralPath $SvmSummaryPath)

function F([object]$Value, [int]$Digits = 6) {
    return [string]::Format([System.Globalization.CultureInfo]::InvariantCulture, ("{0:F" + $Digits + "}"), [double]$Value)
}

function Mean([double[]]$Values) {
    return ($Values | Measure-Object -Average).Average
}

function SampleStd([double[]]$Values) {
    $Average = Mean $Values
    $SumSquares = ($Values | ForEach-Object { ($_ - $Average) * ($_ - $Average) } | Measure-Object -Sum).Sum
    return [Math]::Sqrt($SumSquares / ($Values.Count - 1))
}

$AccuracyOverall = $Overall | Where-Object { $_.metric -eq "accuracy" }
$F1Overall = $Overall | Where-Object { $_.metric -eq "macro_f1" }
$TimeOverall = $Overall | Where-Object { $_.metric -eq "training_wall_seconds" }

$BackendRows = @($Raw | Group-Object backend | ForEach-Object {
    $Rows = @($_.Group)
    $Accuracy = @($Rows | ForEach-Object { [double]$_.accuracy })
    $F1 = @($Rows | ForEach-Object { [double]$_.macro_f1 })
    $Confidence = @($Rows | ForEach-Object { [double]$_.mean_confidence })
    $Time = @($Rows | ForEach-Object { [double]$_.training_wall_seconds })
    [PSCustomObject]@{
        backend = $_.Name
        n_runs = $Rows.Count
        accuracy_mean = Mean $Accuracy
        accuracy_std = SampleStd $Accuracy
        macro_f1_mean = Mean $F1
        macro_f1_std = SampleStd $F1
        confidence_mean = Mean $Confidence
        time_mean = Mean $Time
    }
})

