"""Module 10 — reproducibility report and paper-ready output package."""
from __future__ import annotations

from datetime import datetime, timezone
import json
from pathlib import Path

import pandas as pd

from .analysis import aggregate_results, nps_table
from .config import ExperimentConfig


def _markdown_table(frame: pd.DataFrame) -> str:
    """Render a DataFrame without requiring pandas' optional tabulate dependency."""
    try:
        return frame.to_markdown(index=False)
    except ImportError:
        columns = [str(column) for column in frame.columns]
        lines = ["| " + " | ".join(columns) + " |", "|" + "|".join("---" for _ in columns) + "|"]
        for row in frame.itertuples(index=False, name=None):
            lines.append("| " + " | ".join(str(value) for value in row) + " |")
        return "\n".join(lines)


def generate_report(config: ExperimentConfig, raw_path: Path, output_path: Path | None = None) -> Path:
    output_path = output_path or (config.root / "reports" / "reproducibility_report.md")
    df = pd.DataFrame([json.loads(line) for line in raw_path.read_text(encoding="utf-8").splitlines() if line.strip()])
    agg = aggregate_results(df)
    nps = nps_table(df)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# UniQBench Reproducibility Report",
        "",
        f"Generated at: {datetime.now(timezone.utc).isoformat()}",
        f"Configuration hash: `{config.config_hash()}`",
        "",
        "## Scope",
        "",
        "This report was generated only from the ten UniQBench modules and the raw run records produced by Module 7. No transcript placeholder values are inserted.",
        "",
        "## Experimental configuration",
        "",
        "| Parameter | Value |",
        "|---|---|",
    ]
    for key, value in config.to_dict().items():
        lines.append(f"| {key} | `{value}` |")
    lines += [
        "",
        "## Raw-data summary",
        "",
        f"Raw run records: **{len(df)}**",
        "",
        "| Backend | Runs | Mean accuracy | Accuracy standard deviation | Mean macro-F1 |",
        "|---|---:|---:|---:|---:|",
    ]
    for backend, group in df.groupby("backend"):
        lines.append(
            f"| {backend} | {len(group)} | {group.accuracy.mean():.4f} | {group.accuracy.std(ddof=1) if len(group) > 1 else 0.0:.4f} | {group.macro_f1.mean():.4f} |"
        )
    lines += [
        "",
        "## Backend-by-configuration aggregates",
        "",
        _markdown_table(agg),
        "",
        "## Exploratory Noise Portability Score",
        "",
        "NPS is reported only as an exploratory statistic. It is not interpreted as a universal deployment threshold.",
        "",
        _markdown_table(nps),
        "",
        "## Reproducibility notes",
        "",
        "- Dataset, split, and PCA metadata are generated by Module 2.",
        "- Circuit structure and nominal gate statistics are generated by Module 3.",
        "- Backend execution records are generated by Module 5.",
        "- Training logs and checkpoints are generated by Module 6.",
        "- Raw run-level observations are generated by Module 7.",
        "- Metrics and NPS are generated by Module 8.",
        "- Tables and figures are generated by Module 9.",
        "- This report is generated by Module 10.",
        "",
        "## Scientific limitations",
        "",
        " The MNIST-v1 experiment uses the OpenML mnist_784 dataset restricted to classes 0 and 1. The noisy_shot backend is a transparent shot-and-noise approximation rather than execution on physical quantum hardware. These results are suitable for validating the benchmark software and simulated backend comparison, but they should not be interpreted as evidence of physical-device behavior or quantum advantage.",
    ]
    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return output_path
